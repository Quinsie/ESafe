-- H2 local weather table setup.

CREATE TABLE IF NOT EXISTS TB_WEATHER_ALERT (
    ALERT_SEQ     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ALERT_DATE    DATE DEFAULT CURRENT_DATE,
    ALERT_TYPE    VARCHAR(50),
    ALERT_LEVEL   VARCHAR(20),
    ALERT_CMD     VARCHAR(20),
    REGION_NM     VARCHAR(100),
    REGION_CD     VARCHAR(20),
    PARENT_REGION VARCHAR(100),
    ISSUE_DT      VARCHAR(50),
    EFFECT_DT     VARCHAR(50),
    CANCEL_NOTE   VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS TB_WEATHER_RISK (
    RISK_SEQ       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RISK_DATE      DATE DEFAULT CURRENT_DATE,
    REGION_CD      VARCHAR(20),
    REGION_NM      VARCHAR(100),
    DISTRICT_NM    VARCHAR(50),
    WEATHER_SCORE  DOUBLE,
    APPLIED_ALERTS VARCHAR(500),
    WILDFIRE_SCORE DOUBLE DEFAULT 0,
    WILDFIRE_GRADE VARCHAR(20) DEFAULT 'NONE',
    WILDFIRE_TM    VARCHAR(12)
);

CREATE UNIQUE INDEX IF NOT EXISTS UX_WEATHER_RISK_DATE_REGION
    ON TB_WEATHER_RISK (RISK_DATE, REGION_CD);

ALTER TABLE IF EXISTS TB_WEATHER_RISK
    ADD COLUMN IF NOT EXISTS WILDFIRE_SCORE DOUBLE DEFAULT 0;

ALTER TABLE IF EXISTS TB_WEATHER_RISK
    ADD COLUMN IF NOT EXISTS WILDFIRE_GRADE VARCHAR(20) DEFAULT 'NONE';

ALTER TABLE IF EXISTS TB_WEATHER_RISK
    ADD COLUMN IF NOT EXISTS WILDFIRE_TM VARCHAR(12);

CREATE TABLE IF NOT EXISTS TB_ALERT_ZONE_MAP (
    ZONE_CD       VARCHAR(20) PRIMARY KEY,
    ZONE_NM       VARCHAR(120) NOT NULL,
    PARENT_REGION VARCHAR(120),
    DISTRICT_EXPR VARCHAR(1000),
    SOURCE_TYPE   VARCHAR(30) DEFAULT 'seed',
    USE_YN        CHAR(1) DEFAULT 'Y',
    REG_DT        TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS IDX_ALERT_ZONE_MAP_USE
    ON TB_ALERT_ZONE_MAP (USE_YN);
