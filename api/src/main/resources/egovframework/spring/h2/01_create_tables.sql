-- H2 local table setup (static risk).
-- Keep table names aligned with Oracle runtime SQL.

CREATE TABLE IF NOT EXISTS TB_BUILDING_RISK (
    BLDG_SEQ        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BRANCH_NM       VARCHAR(100),
    A0              VARCHAR(50),
    A13             VARCHAR(200),
    A17             VARCHAR(100),
    A19             VARCHAR(200),
    REGION_NM       VARCHAR(50),
    DISTRICT_NM     VARCHAR(50),
    REGION_CD       VARCHAR(20),
    ADDR            VARCHAR(500),
    LON             DOUBLE,
    LAT             DOUBLE,
    BUILD_YEAR      INT,
    BUILD_AGE       INT,
    A24             VARCHAR(20),
    AGE_GRADE       VARCHAR(10),
    AGE_SCORE       INT,
    FLOOD_GRADE     VARCHAR(10),
    FLOOD_SCORE     INT,
    LANDSLIDE_DIST  DOUBLE,
    LANDSLIDE_GRADE VARCHAR(10),
    LANDSLIDE_SCORE INT,
    FIRE_SCORE      INT,
    PREV_FIRE_OCCUR_DATE VARCHAR(1000),
    LAND_USE_SCORE  INT,
    TOTAL_SCORE     DOUBLE,
    TOTAL_GRADE     VARCHAR(10),
    RISK_CD         VARCHAR(5),
    RISK_DATE       DATE DEFAULT CURRENT_DATE,
    ANAL_DATE       VARCHAR(20),
    REG_DT          TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Oracle compatibility alias for mapper SQL.
CREATE VIEW IF NOT EXISTS TB_BLDG_RISK_STATIC AS
SELECT * FROM TB_BUILDING_RISK;

ALTER TABLE IF EXISTS TB_BUILDING_RISK
    ADD COLUMN IF NOT EXISTS LANDSLIDE_DIST DOUBLE;
