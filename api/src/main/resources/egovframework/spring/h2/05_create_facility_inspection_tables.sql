-- H2 local facility inspection history setup.

CREATE TABLE IF NOT EXISTS TB_FACILITY_GENERAL_HIST (
    HIST_SEQ              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BLDG_SEQ              BIGINT NOT NULL,
    BRANCH_NM             VARCHAR(100),
    ADDR                  VARCHAR(500),
    KEPCO_CUST_NO         VARCHAR(50),
    CHECK_RESULT          VARCHAR(20) NOT NULL,
    ORAL_NOTICE_YN        CHAR(1),
    NONCONFORMITY_DETAIL  VARCHAR(1000),
    LINE_NO               VARCHAR(100),
    CAPACITY              VARCHAR(100),
    CHECK_CYCLE           VARCHAR(100),
    CONTRACT_TYPE         VARCHAR(200),
    CHECK_DT              DATE NOT NULL,
    RAW_JSON              CLOB,
    REG_DT                TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_FACILITY_GENERAL_ORAL_YN
        CHECK (ORAL_NOTICE_YN IN ('Y', 'N') OR ORAL_NOTICE_YN IS NULL)
);

CREATE INDEX IF NOT EXISTS IDX_FACILITY_GENERAL_BLDG
    ON TB_FACILITY_GENERAL_HIST (BLDG_SEQ, CHECK_DT);
CREATE INDEX IF NOT EXISTS IDX_FACILITY_GENERAL_CUST
    ON TB_FACILITY_GENERAL_HIST (BLDG_SEQ, KEPCO_CUST_NO);
CREATE INDEX IF NOT EXISTS IDX_FACILITY_GENERAL_LATEST
    ON TB_FACILITY_GENERAL_HIST (BLDG_SEQ, KEPCO_CUST_NO, CHECK_DT, REG_DT, HIST_SEQ);
CREATE INDEX IF NOT EXISTS IDX_FACILITY_GENERAL_SCORE_SCAN
    ON TB_FACILITY_GENERAL_HIST (BLDG_SEQ, CHECK_RESULT, KEPCO_CUST_NO, CHECK_DT, REG_DT, HIST_SEQ);

CREATE TABLE IF NOT EXISTS TB_FACILITY_SELF_HIST (
    HIST_SEQ              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BLDG_SEQ              BIGINT NOT NULL,
    BRANCH_NM             VARCHAR(100),
    ADDR                  VARCHAR(500),
    KEPCO_CUST_NO         VARCHAR(50),
    INSPECTION_RESULT     VARCHAR(20) NOT NULL,
    FAIL_DETAIL           VARCHAR(1000),
    DEFECT_CNT            INT,
    MOTOR_TYPE            VARCHAR(200),
    CHECK_DT              DATE NOT NULL,
    RAW_JSON              CLOB,
    REG_DT                TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS IDX_FACILITY_SELF_BLDG
    ON TB_FACILITY_SELF_HIST (BLDG_SEQ, CHECK_DT);
CREATE INDEX IF NOT EXISTS IDX_FACILITY_SELF_CUST
    ON TB_FACILITY_SELF_HIST (BLDG_SEQ, KEPCO_CUST_NO);
CREATE INDEX IF NOT EXISTS IDX_FACILITY_SELF_LATEST
    ON TB_FACILITY_SELF_HIST (BLDG_SEQ, KEPCO_CUST_NO, CHECK_DT, REG_DT, HIST_SEQ);
CREATE INDEX IF NOT EXISTS IDX_FACILITY_SELF_SCORE_SCAN
    ON TB_FACILITY_SELF_HIST (BLDG_SEQ, INSPECTION_RESULT, KEPCO_CUST_NO, CHECK_DT, REG_DT, HIST_SEQ);

ALTER TABLE IF EXISTS TB_FACILITY_SELF_HIST
    ADD COLUMN IF NOT EXISTS DEFECT_CNT INT;
ALTER TABLE IF EXISTS TB_FACILITY_SELF_HIST
    ADD COLUMN IF NOT EXISTS MOTOR_TYPE VARCHAR(200);
ALTER TABLE IF EXISTS TB_FACILITY_SELF_HIST
    ADD COLUMN IF NOT EXISTS RAW_JSON CLOB;

ALTER TABLE IF EXISTS TB_FACILITY_GENERAL_HIST
    ADD COLUMN IF NOT EXISTS LINE_NO VARCHAR(100);
ALTER TABLE IF EXISTS TB_FACILITY_GENERAL_HIST
    ADD COLUMN IF NOT EXISTS CAPACITY VARCHAR(100);
ALTER TABLE IF EXISTS TB_FACILITY_GENERAL_HIST
    ADD COLUMN IF NOT EXISTS CHECK_CYCLE VARCHAR(100);
ALTER TABLE IF EXISTS TB_FACILITY_GENERAL_HIST
    ADD COLUMN IF NOT EXISTS CONTRACT_TYPE VARCHAR(200);
ALTER TABLE IF EXISTS TB_FACILITY_GENERAL_HIST
    ADD COLUMN IF NOT EXISTS RAW_JSON CLOB;
